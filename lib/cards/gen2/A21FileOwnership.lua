function M.filesFor(owner, extras)
  local result, seen = {}, {}
  for path, assigned in pairs(OWNER) do
    if assigned == owner then result[#result + 1], seen[path] = path, true end
  end
  for _, path in ipairs(extras or {}) do
    -- The complete A21 ledger is authoritative for gen2/**. Extras add only
    -- root adapters/Card infrastructure that are outside that imported tree.
    if OWNER[path] == nil and not seen[path] then
      result[#result + 1], seen[path] = path, true
    end
  end
  table.sort(result)
  return result
end

function M.owner(path) return OWNER[path] end
function M.count()
  local count = 0
  for _ in pairs(OWNER) do count = count + 1 end
  return count
end

return M
