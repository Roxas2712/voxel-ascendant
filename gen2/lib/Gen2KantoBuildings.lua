function P.borderEntrances(map)
 local out={};local d=map and map.def
 if not(d and d.generation==2 and d.tileset=='TILESET_KANTO'
  and (d.environment=='TOWN' or d.environment=='ROUTE')
  and type(map.cellCollision)=='function' and type(map.tileAt)=='function')then return out end
 for _,p in ipairs(borderDoors[map.id]or{})do
  local c=d.connections and d.connections[p.edge]
  local valid=d.width==p.width and d.height==p.height and c
   and c.mapId==p.neighbor and c.offset==p.offset
  for i=0,1 do
   local x=p.x+(p.axis=='x' and i or 0);local y=p.y+(p.axis=='y' and i or 0)
   local hits=0
   for _,w in ipairs(d.warps or{})do if w.x==x and w.y==y then
    hits=hits+1
    if w.destMap~=p.destination or type(w.destWarp)~='number' or w.destWarp<1 then valid=false end
   end end
   if hits~=1 or map:cellCollision(x,y)~=p.collision then valid=false end
   for dy=0,1 do for dx=0,1 do if map:tileAt(x*2+dx,y*2+dy)~=0x4f then valid=false end end end
  end
  if valid then out[#out+1]=p end
 end
 return out
end
function P.stampBorderEntrances(S,map)
 local aw,ah=map.tileset.imageWidth or 128,map.tileset.imageHeight or 48
 local course={0x0b,0x0c,0x1b,0x1c}
 for _,p in ipairs(P.borderEntrances(map))do
  for row=0,1 do for col=0,1 do
   local t=course[row*2+col+1];local px,py=(t%16)*8,math.floor(t/16)*8
   local y=(1-row)*8;local q
   if p.face=='north'then
    local x=p.x*16+8+(1-col)*8;local z=p.height*32-.02
    q={{x+8,y,z},{x,y,z},{x,y+8,z},{x+8,y+8,z},shade=.68}
   else
    local x=p.face=='east' and .02 or p.width*32-.02
    local z=p.y*16+8+(p.face=='west' and col or 1-col)*8
    local a,b=z,z+8;if p.face=='east'then a,b=b,a end
    q={{x,y,a},{x,y,b},{x,y+8,b},{x,y+8,a},shade=.78}
   end
   q.uv={{px/aw,(py+8)/ah},{(px+8)/aw,(py+8)/ah},
    {(px+8)/aw,py/ah},{px/aw,py/ah}};q.own=true
   S.objectQuads[#S.objectQuads+1]=q
  end end
 end
end
