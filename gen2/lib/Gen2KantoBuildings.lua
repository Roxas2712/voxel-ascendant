 local p=rearDoors[id]
 if not(p and d and d.generation==2 and d.tileset=='TILESET_KANTO'
  and tx==p.tx and ty==p.ty and t and t.tiles
  and #t.tiles==p.bh and #t.tiles[1]==p.bw)then return false end
 if d.width~=p.width or d.height~=p.height or not map.cellCollision or not map.tileAt then return true end
 for i=0,1 do
  local hits=0
  for _,w in ipairs(d.warps or{})do if w.x==p.x+i and w.y==p.y then
   if w.destMap~=p.destination or type(w.destWarp)~='number' or w.destWarp<1 then return true end
   hits=hits+1
  end end
  if hits~=1 or map:cellCollision(p.x+i,p.y)~=0x70 then return true end
  for dy=0,1 do for dx=0,1 do if map:tileAt((p.x+i)*2+dx,p.y*2+dy)~=0x4f then return true end end end
 end
 return true,{x=p.x*16+8-tx*8,tiles={0x0b,0x0c,0x1b,0x1c}}
